// The levels, as text: see LEGEND, THINGS and PLATFORM in level.ts:
//   '#' ground, 'X' block, 'B' brick, '?' bonus block, '!' power block (a
//   battery, or a thruster for big Bit), '*' star block, '^' spikes,
//   'o' coin, '$' big coin (three per level, hidden), 'g' walker, 'k' shell,
//   'v' flyer, 'C' checkpoint, 'S' start, 'F' goal flag,
//   '=' platform ('-' its track across, '|' its track up and down),
//   '~' platform that falls.
// Each level is written as pieces side by side, bottom-aligned (the last two
// lines of a piece are the ground), so a piece only needs its lowest lines.
import { LevelSpec, Theme } from './level';

/** Rows in every level: room above for high jumps and the camera. */
const HEIGHT = 16;

/** Joins pieces of text side by side into a level, padding each piece to its widest line and up to HEIGHT. */
function level(name: string, theme: Theme, ...pieces: string[]): LevelSpec {
  const rows = Array<string>(HEIGHT).fill('');
  for (const piece of pieces) {
    const lines = piece.split('\n').map((l) => l.trim()).filter((l) => l.length);
    if (lines.length > HEIGHT) throw new Error(`${name}: a piece is ${lines.length} rows high`);
    const width = Math.max(...lines.map((l) => l.length));
    const padded = [...Array(HEIGHT - lines.length).fill(''), ...lines].map((l) => l.padEnd(width, '.'));
    padded.forEach((l, r) => { rows[r] += l; });
  }
  return { name, theme, rows };
}

