// Embeds src/shaders/glsl/**/*.{vert,frag,glsl} into src/shaders/embedded-shaders.ts,
// keyed by the URI that ShaderSources uses (assets/shaders/<path>), so the
// engine serves its shaders without fetching them from the host app.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const glslDir = join(root, 'src/shaders/glsl');
const out = join(root, 'src/shaders/embedded-shaders.ts');

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.(vert|frag|glsl)$/.test(name)) files.push(path);
  }
};
walk(glslDir);

const entries = files.map((path) => {
  const key = 'assets/shaders/' + relative(glslDir, path).split('\\').join('/');
  return `  ${JSON.stringify(key)}: ${JSON.stringify(readFileSync(path, 'utf8'))},`;
});

writeFileSync(
  out,
  `/* eslint-disable */
// Generated by scripts/embed-shaders.mjs from src/shaders/glsl. Do not edit:
// change the .vert/.frag files and run \`npm run embed-shaders\`.

/** GLSL sources shipped with the engine, keyed by their ShaderSources URI. */
export const EMBEDDED_SHADERS: { readonly [uri: string]: string } = {
${entries.join('\n')}
};
`,
);
console.log(`Embedded ${files.length} shaders into ${relative(root, out)}`);
